/** Reads quoted multiline TSV/CSV, including the source's unescaped inner quotes. */
export function parseProposalTable(source: string): ProposalSourceRow[] {
  const text = source.replace(/^\uFEFF/, "");
  const delimiter = text
    .slice(0, text.indexOf("\n") < 0 ? undefined : text.indexOf("\n"))
    .includes("\t")
    ? "\t"
    : ",";
  const records: string[][] = [];
  let record: string[] = [],
    field = "",
    quoted = false;
  const flush = () => {
    record.push(field);
    field = "";
    if (record.some((cell) => cell.trim())) records.push(record);
    record = [];
  };
  for (let index = 0; index < text.length; index++) {
    const character = text[index],
      next = text[index + 1];
    if (quoted) {
      if (character === '"' && next === '"') {
        field += '"';
        index++;
      } else if (
        character === '"' &&
        (next === delimiter ||
          next === "\r" ||
          next === "\n" ||
          next === undefined)
      )
        quoted = false;
      else field += character;
    } else if (character === '"' && !field) quoted = true;
    else if (character === delimiter) {
      record.push(field);
      field = "";
    } else if (character === "\r" || character === "\n") {
      flush();
      if (character === "\r" && next === "\n") index++;
    } else field += character;
  }
  if (quoted) throw new Error("يوجد حقل مقتبس غير مكتمل في ملف الأفكار.");
  if (field || record.length) flush();
  const headers = records.shift()?.map((header) => header.trim());
  if (
    !headers ||
    headers.length !== PROPOSAL_HEADERS.length ||
    headers.some((header, index) => header !== PROPOSAL_HEADERS[index])
  )
    throw new Error("عناوين جدول الأفكار لا تطابق المصدر المتوقع.");
  return records.map((cells, index) => {
    if (cells.length !== 8)
      throw new Error(
        `الصف ${index + 1} يحتوي ${cells.length} حقول بدلاً من 8؛ لم يتم استيراد بيانات ناقصة.`,
      );
    if (!cells[3].trim()) throw new Error(`الفكرة في الصف ${index + 1} فارغة.`);
    return {
      row: index + 1,
      proposer: cells[0],
      funding: cells[1],
      goal: cells[2],
      concept: cells[3],
      contentType: cells[4],
      platform: cells[5],
      reference: cells[6],
      approval: cells[7],
    };
  });
}

