function addDays(date: string, days: number): string {
  if (
    !/^\d{4}-\d{2}-\d{2}$/.test(date) ||
    !Number.isFinite(Date.parse(`${date}T12:00:00Z`))
  )
    throw new Error("تاريخ الطلب غير صالح.");
  const result = new Date(`${date}T12:00:00Z`);
  result.setUTCDate(result.getUTCDate() + days);
  return result.toISOString().slice(0, 10);
}

export function buildProposalIdeas(
  rows: ProposalSourceRow[],
  data: MediaData,
  today = PROPOSAL_REQUEST_DATE,
): Idea[] {
  if (rows.length !== BLUEPRINTS.length)
    throw new Error(
      `المصدر المتوقع 27 فكرة؛ وُجد ${rows.length}. لا تُستورد دفعة جزئية أو محاذاة غير مؤكدة.`,
    );
  const createdAt = `${today}T09:00:00.000Z`;
  return rows.map((source, index) => {
    const blueprint = BLUEPRINTS[index];
    if (source.row !== index + 1 || !source.concept.includes(blueprint.match))
      throw new Error(
        `لا يطابق مضمون الصف ${source.row} خطة الإثراء؛ راجع المصدر قبل الاستيراد.`,
      );
    const proposerName = source.proposer.trim() || "غير مذكور في المصدر";
    if (!["يوسف", "سارة", "غير مذكور في المصدر"].includes(proposerName))
      throw new Error(`مقدم غير معروف في الصف ${source.row}: ${proposerName}`);
    const ownerId = proposerName === "سارة" ? "sara" : "root";
    const companyId = blueprint.companyId || "mawaredcom";
    const company = data.companies.find((item) => item.id === companyId);
    if (
      !company ||
      !data.categories.some((item) => item.id === blueprint.categoryId)
    )
      throw new Error(`شركة أو تصنيف مطلوب غير موجود للصف ${source.row}.`);
    const companyNote = blueprint.companyId
      ? `الشركة المستفيدة المقترحة: ${company.name}، لورود اسم هيّن في المصدر؛ تؤكد الجهة قبل النشر.`
      : `الشركة المستفيدة المقترحة مؤقتاً: ${company.name}. لم يحدد المصدر شركة؛ يمكن اعتماد الشركة المستفيدة قبل النشر.`;
    const authorNote =
      proposerName === "غير مذكور في المصدر"
        ? "لم يذكر مقدم الفكرة في المصدر. أُسندت المتابعة إلى يوسف للتنسيق فقط، ولا تُنسب إليه فكرة المصدر."
        : `مقدم الفكرة في المصدر: ${proposerName}. مسؤول المحتوى المكلّف يتابع التنسيق؛ إسناد المهمة منفصل عن ملكية الفكرة.`;
    const reviewNote = [
      blueprint.reviewNote,
      proposerName === "غير مذكور في المصدر" ? authorNote : "",
    ]
      .filter(Boolean)
      .join("\n");
    const sourceProposal: SourceProposal = {
      batchId: PROPOSAL_BATCH_ID,
      row: source.row,
      proposerName,
      funding: source.funding,
      originalGoal: source.goal,
      originalConcept: source.concept,
      sourceApproval: source.approval,
      ...(reviewNote ? { reviewNote } : {}),
    };
    const rowNumber = String(source.row).padStart(2, "0"),
      id = `proposal-20261008-${rowNumber}`;
    const outputNotes = blueprint.channels
      .map((channel) =>
        channel === "screens"
          ? "الشاشات: نسخة أفقية 16:9."
          : channel === "whatsapp"
            ? "واتساب: نسخة عمودية 9:16؛ تقسم البطاقات الطويلة بما يحافظ على القراءة."
            : "البريد: بطاقة ثابتة ملائمة للعرض على الهاتف والبريد الداخلي.",
      )
      .join("\n");
    return {
      id,
      code: `IC-2026-P${String(source.row).padStart(3, "0")}`,
      title: blueprint.title,
      companyId,
      department: "فريق التواصل الداخلي — مقترح داخلي",
      categoryId: blueprint.categoryId,
      workType: blueprint.workType,
      description: `${companyNote}\n\n${authorNote}\n\nالهدف: ${blueprint.goal}\n\nشرح الفكرة:\n${blueprint.description}${reviewNote ? `\n\nملاحظات قبل الاعتماد:\n${reviewNote}` : ""}\n\nهذه مسودة مقترحة من القائمة الأصلية؛ المواعيد والقنوات والصياغة قابلة للمراجعة قبل الاعتماد.`,
      content: blueprint.content,
      executionPlan: `${blueprint.steps.map((step, number) => `${number + 1}. ${step}`).join("\n\n")}\n\nالمخرجات المطلوبة:\n${outputNotes}\n\nالاعتماد والأرشفة: اعتماد النص والخطة داخل النظام، ثم جدولة التنفيذ بواسطة فريق التصميم، ومراجعة جميع النسخ قبل التسليم وإرفاق الملفات النهائية لكل قناة.`,
      channels: [...blueprint.channels],
      ownerId,
      designerId: "",
      requestedAt: today,
      dueDate: addDays(today, blueprint.leadDays),
      scheduledAt: "",
      priority: "normal",
      status: "draft",
      needsQuotes: !!blueprint.needsQuotes,
      quotations: [],
      attachments: [],
      managerFeedback: "",
      sourceProposal,
      history: [
        {
          id: `${id}-created`,
          at: createdAt,
          actorId: "root",
          action: "created",
          to: "draft",
          note: `استيراد مسودة من الصف ${source.row} في قائمة الأفكار، مع حفظ صاحب المقترح والنص الأصلي دون اعتماد تشغيلي.${source.approval.trim() ? ` حالة المصدر: ${source.approval.trim()}؛ ليست اعتماداً داخل النظام.` : ""}\nبيانات المصدر الإضافية: ${JSON.stringify({ contentType: source.contentType, platform: source.platform, reference: source.reference })}`,
        },
      ],
      createdAt,
      updatedAt: createdAt,
    };
  });
}

export function proposalImportSummary(ideas: Idea[]) {
  const authors: Record<string, number> = {},
    workTypes: Record<string, number> = {},
    categories: Record<string, number> = {};
  for (const idea of ideas) {
    const author = idea.sourceProposal?.proposerName || "غير مذكور في المصدر";
    authors[author] = (authors[author] || 0) + 1;
    workTypes[idea.workType] = (workTypes[idea.workType] || 0) + 1;
    categories[idea.categoryId] = (categories[idea.categoryId] || 0) + 1;
  }
  return {
    count: ideas.length,
    authors,
    workTypes,
    categories,
    requiresQuotations: ideas
      .filter((idea) => idea.needsQuotes)
      .map((idea) => ({ row: idea.sourceProposal!.row, title: idea.title })),
    sourceApprovedOnly: ideas
      .filter((idea) => idea.sourceProposal?.sourceApproval.trim())
      .map((idea) => ({
        row: idea.sourceProposal!.row,
        sourceApproval: idea.sourceProposal!.sourceApproval,
      })),
    unspecifiedCompanies: ideas.filter(
      (idea) => idea.companyId === "mawaredcom",
    ).length,
    missingAuthors: ideas
      .filter(
        (idea) => idea.sourceProposal?.proposerName === "غير مذكور في المصدر",
      )
      .map((idea) => idea.sourceProposal!.row),
    rows: ideas.map((idea) => ({
      row: idea.sourceProposal!.row,
      title: idea.title,
      proposerName: idea.sourceProposal!.proposerName,
      ownerId: idea.ownerId,
      companyId: idea.companyId,
      dueDate: idea.dueDate,
      status: idea.status,
      reviewNote: idea.sourceProposal!.reviewNote || "",
    })),
  };
}

/** Appends only absent rows; never replaces user edits, roster names, or settings. */
export function appendProposalImport(data: MediaData, proposals: Idea[]) {
  const root = data.members.find((member) => member.id === "root"),
    sara = data.members.find((member) => member.id === "sara");
  if (
    !root?.active ||
    root.role !== "superadmin" ||
    !sara?.active ||
    !["content", "admin", "superadmin"].includes(sara.role)
  )
    throw new Error(
      "جهّز حساب root الفعّال ومسؤول المحتوى sara قبل تطبيق الاستيراد؛ ملف المراجعة لا ينشئ حسابات.",
    );
  const added: Idea[] = [],
    skipped: string[] = [];
  for (const proposal of proposals) {
    const provenance = proposal.sourceProposal!;
    const existing = data.ideas.find(
      (idea) =>
        idea.id === proposal.id ||
        (idea.sourceProposal?.batchId === provenance.batchId &&
          idea.sourceProposal.row === provenance.row),
    );
    if (existing) {
      if (
        existing.sourceProposal?.batchId !== provenance.batchId ||
        existing.sourceProposal.row !== provenance.row ||
        existing.sourceProposal.originalConcept !==
          provenance.originalConcept ||
        existing.sourceProposal.originalGoal !== provenance.originalGoal ||
        existing.sourceProposal.proposerName !== provenance.proposerName ||
        existing.sourceProposal.funding !== provenance.funding ||
        existing.sourceProposal.sourceApproval !== provenance.sourceApproval ||
        existing.history.find((event) => event.id === `${proposal.id}-created`)
          ?.note !== proposal.history[0].note
      )
        throw new Error(
          `تعارض مصدر أو معرّف عند الصف ${provenance.row}. لم يُكتب فوق السجل الموجود.`,
        );
      skipped.push(existing.id);
      continue;
    }
    if (data.ideas.some((idea) => idea.code === proposal.code))
      throw new Error(
        `رمز العمل ${proposal.code} مستخدم؛ لم يُغيّر السجل الموجود.`,
      );
    added.push(proposal);
  }
  const result = { ...data, ideas: [...added, ...data.ideas] };
  validateMediaData(result);
  return { data: result, added, skipped };
}
